export type FixtureBoot = "serve" | "crash" | "hang" | "ignore-port";

export function previewDevServerSource(): string {
  return [
    'import { createServer } from "node:http";',
    'import { readFileSync } from "node:fs";',
    'import { DatabaseSync } from "node:sqlite";',
    "",
    "function bootMode() {",
    "  try {",
    '    return readFileSync("BOOT.txt", "utf8").trim();',
    "  } catch {",
    '    return "serve";',
    "  }",
    "}",
    "",
    "function withDb(fn) {",
    "  const dbPath = process.env.DEMO_DB;",
    "  if (!dbPath) return null;",
    "  const db = new DatabaseSync(dbPath);",
    '  db.exec("PRAGMA busy_timeout = 3000");',
    "  try {",
    "    return fn(db);",
    "  } finally {",
    "    db.close();",
    "  }",
    "}",
    "",
    "const mode = bootMode();",
    "if (mode === 'crash') {",
    '  console.error("preview boot crashed " + (process.env.STRIPE_TEST_KEY ?? ""));',
    "  process.exit(1);",
    "}",
    "",
    "const port = Number(process.env.PORT);",
    "if (!Number.isInteger(port) || port < 41000 || port > 48999) {",
    '  console.error("app ignores PORT");',
    "  process.exit(1);",
    "}",
    "",
    "const server = createServer((req, res) => {",
    "  const url = new URL(req.url ?? '/', 'http://127.0.0.1');",
    "  if (req.method === 'GET' && (url.pathname === '/' || url.pathname === '/api/health')) {",
    "    res.writeHead(200, {",
    "      'content-type': 'text/html; charset=utf-8',",
    "      'x-ef-preview-sha': process.env.EF_PREVIEW_SHA ?? '',",
    "    });",
    "    res.end('<!doctype html><title>Live Preview</title><p>orders</p>');",
    "    return;",
    "  }",
    "  if (req.method === 'GET' && url.pathname === '/@vite/client') {",
    "    res.writeHead(200, { 'content-type': 'text/javascript' });",
    "    res.end('export const hot = true;\\n');",
    "    return;",
    "  }",
    "  if (req.method === 'GET' && url.pathname === '/cwd-marker') {",
    '    const marker = readFileSync("MARKER.txt", "utf8").trim();',
    "    res.writeHead(200, { 'content-type': 'application/json' });",
    "    res.end(JSON.stringify({ marker, cwd: process.cwd() }));",
    "    return;",
    "  }",
    "  if (req.method === 'GET' && url.pathname === '/env-flags') {",
    "    res.writeHead(200, { 'content-type': 'application/json' });",
    "    res.end(JSON.stringify({",
    '      stripeTest: typeof process.env.STRIPE_TEST_KEY === "string",',
    '      parentCanary: typeof process.env.PARENT_CANARY === "string",',
    '      smtp: typeof process.env.SMTP_URL === "string",',
    '      s3: typeof process.env.S3_ENDPOINT === "string",',
    '      oauth: typeof process.env.OAUTH_ISSUER === "string",',
    "    }));",
    "    return;",
    "  }",
    "  if (req.method === 'GET' && url.pathname === '/orders') {",
    '    const rows = withDb((db) => db.prepare("SELECT * FROM orders ORDER BY id").all()) ?? [];',
    "    res.writeHead(200, { 'content-type': 'application/json' });",
    "    res.end(JSON.stringify(rows));",
    "    return;",
    "  }",
    "  if (req.method === 'GET' && url.pathname === '/meta') {",
    '    const rows = withDb((db) => db.prepare("SELECT key, value FROM demo_meta").all()) ?? [];',
    "    res.writeHead(200, { 'content-type': 'application/json' });",
    "    res.end(JSON.stringify(rows));",
    "    return;",
    "  }",
    "  if (req.method === 'POST' && url.pathname === '/orders') {",
    "    const chunks = [];",
    "    req.on('data', (chunk) => chunks.push(chunk));",
    "    req.on('end', () => {",
    "      try {",
    "        const body = JSON.parse(Buffer.concat(chunks).toString('utf8'));",
    "        withDb((db) => db.prepare('INSERT INTO orders (id, note) VALUES (?, ?)').run(String(body.id), String(body.note)));",
    "        res.writeHead(201, { 'content-type': 'application/json' });",
    "        res.end(JSON.stringify({ ok: true }));",
    "      } catch (error) {",
    "        res.writeHead(400, { 'content-type': 'text/plain' });",
    "        res.end(error instanceof Error ? error.message : 'bad order');",
    "      }",
    "    });",
    "    return;",
    "  }",
    "  res.writeHead(404);",
    "  res.end();",
    "});",
    "",
    "server.on('error', (error) => {",
    "  console.error(error instanceof Error ? error.message : 'listen failed');",
    "  process.exit(1);",
    "});",
    "",
    "if (mode === 'hang') {",
    "  setInterval(() => {}, 1000);",
    "} else {",
    "  const bindPort = mode === 'ignore-port' ? 0 : port;",
    "  server.listen(bindPort, '127.0.0.1');",
    "}",
    "",
  ].join("\n");
}

export function expenseCliSource(): string {
  return [
    'import { DatabaseSync } from "node:sqlite";',
    "",
    "const dbPath = process.env.DEMO_DB;",
    "if (!dbPath) {",
    '  console.error("missing DEMO_DB");',
    "  process.exit(1);",
    "}",
    "const db = new DatabaseSync(dbPath);",
    'db.exec("PRAGMA busy_timeout = 3000");',
    "const cmd = process.argv[2];",
    "if (cmd === 'add') {",
    "  db.prepare('INSERT INTO orders (id, note) VALUES (?, ?)').run(process.argv[3], process.argv[4]);",
    "  console.log('added');",
    "} else if (cmd === 'list') {",
    '  console.log(JSON.stringify(db.prepare("SELECT id, note FROM orders ORDER BY id").all()));',
    "} else if (cmd === 'cwd') {",
    "  console.log(process.cwd());",
    "} else if (cmd === 'env-has') {",
    "  console.log(process.env[process.argv[3]] ? 'yes' : 'no');",
    "} else {",
    "  console.error('unknown command');",
    "  db.close();",
    "  process.exit(2);",
    "}",
    "db.close();",
    "",
  ].join("\n");
}


import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { BrandAssetRegistry } from "./brand-asset-registry.js";
import type { StoredBrandAsset } from "./brand-record.js";
import { scanUnapprovedHotlinks, type HotlinkFinding } from "./hotlink-scanner.js";
import { NEUTRAL_BRAND_TOKENS, VISUAL_BRAND_ROLES, type BrandAssetRole, type BrandColorTokens } from "./limits.js";
import { DeterministicPlaceholderGenerator } from "./placeholders.js";

const MODULE_KEY: Record<BrandAssetRole, string> = {
  logo_light: "logoLight",
  logo_dark: "logoDark",
  favicon: "favicon",
  hero: "hero",
  avatar_fallback: "avatarFallback",
  font: "font",
};

const FILE_STEM: Record<BrandAssetRole, string> = {
  logo_light: "logo-light",
  logo_dark: "logo-dark",
  favicon: "favicon",
  hero: "hero",
  avatar_fallback: "avatar-fallback",
  font: "font-brand",
};

export interface Phase0EmitResult {
  readonly assetsTsPath: string;
  readonly assetsTs: string;
  readonly files: readonly string[];
  readonly checklist: readonly string[];
  readonly hotlinks: readonly HotlinkFinding[];
}

export class Phase0BrandAssetsGenerator {
  private readonly placeholders: DeterministicPlaceholderGenerator;

  constructor(private readonly registry: BrandAssetRegistry, placeholders = new DeterministicPlaceholderGenerator()) {
    this.placeholders = placeholders;
  }

  async emit(input: {
    readonly appRoot: string;
    readonly projectName: string;
    readonly destination?: "public" | "src-assets";
    readonly tokens?: BrandColorTokens;
  }): Promise<Phase0EmitResult> {
    const destination = input.destination ?? "public";
    const tokens = input.tokens ?? NEUTRAL_BRAND_TOKENS;
    const generated = await this.placeholders.generate(input.projectName, tokens);
    for (const role of VISUAL_BRAND_ROLES) {
      if (!this.registry.get(role)) {
        const asset = generated.assets[role];
        await this.registry.registerPrepared(asset);
      }
    }
    const roles: BrandAssetRole[] = [...VISUAL_BRAND_ROLES];
    if (this.registry.get("font")) roles.push("font");
    const directory = destination === "public"
      ? path.join(input.appRoot, "public", "brand")
      : path.join(input.appRoot, "src", "assets", "brand");
    mkdirSync(directory, { recursive: true });
    mkdirSync(path.join(input.appRoot, "src", "brand"), { recursive: true });
    const files: string[] = [];
    const entries: string[] = [];
    const checklist: string[] = [];
    for (const role of roles) {
      const stored = this.registry.get(role);
      if (!stored) continue;
      const filename = `${FILE_STEM[role]}.${extensionFor(stored.mimeType)}`;
      const absolute = path.join(directory, filename);
      writeFileSync(absolute, this.registry.readBytes(role));
      files.push(absolute);
      const src = destination === "public" ? `/brand/${filename}` : `src/assets/brand/${filename}`;
      entries.push(renderEntry(MODULE_KEY[role], stored, src));
      if (stored.placeholder) checklist.push(generated.checklist.find((line) => line.startsWith(role)) ?? `${role} is still a placeholder.`);
    }
    const assetsTs = renderModule(entries, checklist);
    const assetsTsPath = path.join(input.appRoot, "src", "brand", "assets.ts");
    writeFileSync(assetsTsPath, assetsTs);
    const hotlinks = scanUnapprovedHotlinks(assetsTs, { projectRoot: input.appRoot });
    if (hotlinks.length > 0) {
      throw new Error(`src/brand/assets.ts contains ${hotlinks.length} unapproved image reference(s)`);
    }
    for (const file of files) {
      if (!fileExists(file)) throw new Error(`Brand asset file is missing after emit: ${file}`);
    }
    return { assetsTsPath, assetsTs, files, checklist, hotlinks };
  }
}

function renderModule(entries: readonly string[], checklist: readonly string[]): string {
  return [
    "/**",
    " * Generated by Phase0BrandAssetsGenerator.",
    " * Frontend code must import these symbols. Do not invent /logo.png or hotlink a stock CDN.",
    " */",
    "export interface BrandAssetModuleEntry {",
    "  readonly src: string;",
    "  readonly width: number;",
    "  readonly height: number;",
    "  readonly alt: string;",
    "  readonly placeholder: boolean;",
    "  readonly role: \"logo_light\" | \"logo_dark\" | \"favicon\" | \"hero\" | \"avatar_fallback\" | \"font\";",
    "  readonly mimeType: string;",
    "  readonly casSha256: string;",
    "}",
    "",
    "export const BRAND_ASSETS = {",
    entries.join("\n"),
    "} as const satisfies Record<string, BrandAssetModuleEntry>;",
    "",
    "export const PLACEHOLDER_SHIP_CHECKLIST = [",
    checklist.map((line) => `  ${JSON.stringify(line)},`).join("\n"),
    "] as const;",
    "",
  ].join("\n");
}

function renderEntry(key: string, asset: StoredBrandAsset, src: string): string {
  return [
    `  ${key}: {`,
    `    src: ${JSON.stringify(src)},`,
    `    width: ${asset.width},`,
    `    height: ${asset.height},`,
    `    alt: ${JSON.stringify(asset.altText)},`,
    `    placeholder: ${asset.placeholder ? "true" : "false"},`,
    `    role: ${JSON.stringify(asset.role)},`,
    `    mimeType: ${JSON.stringify(asset.mimeType)},`,
    `    casSha256: ${JSON.stringify(asset.casSha256)},`,
    "  },",
  ].join("\n");
}

function extensionFor(mimeType: string): string {
  switch (mimeType) {
    case "image/svg+xml":
      return "svg";
    case "image/jpeg":
      return "jpg";
    case "image/webp":
      return "webp";
    case "image/avif":
      return "avif";
    case "font/woff2":
      return "woff2";
    case "font/woff":
      return "woff";
    case "font/otf":
      return "otf";
    case "font/ttf":
      return "ttf";
    default:
      return "png";
  }
}

function fileExists(file: string): boolean {
  return existsSync(file) && statSync(file).isFile();
}
